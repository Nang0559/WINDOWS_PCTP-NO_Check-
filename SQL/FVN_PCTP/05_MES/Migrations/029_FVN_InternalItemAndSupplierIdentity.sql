/*
 Migration 029: FVN-owned ItemId5 and SupplierId5 identities.
 - IFS remains read-only; IFS business keys are retained unchanged.
 - Internal numeric IDENTITY keys are generated by FVN_PCTP.
 - Five-character LOT tokens are separate, stable, unique base-36 codes.
 - Existing ItemId5 values allocated by migration 028 are preserved.
 SQL Server 2016 compatible.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;

IF DB_NAME() <> N'FVN_PCTP'
    THROW 52900, 'Migration 029 may run only in FVN_PCTP.', 1;
IF OBJECT_ID(N'MES.FVN_SchemaMigration', N'U') IS NULL
    THROW 52901, 'MES.FVN_SchemaMigration is missing.', 1;
IF NOT EXISTS (SELECT 1 FROM MES.FVN_SchemaMigration WHERE MigrationVersion='028')
    THROW 52902, 'Migration 028 must be applied before migration 029.', 1;
IF EXISTS (SELECT 1 FROM MES.FVN_SchemaMigration WHERE MigrationVersion='029')
    RETURN;
IF OBJECT_ID(N'dbo.FVN_PartIdentity',N'U') IS NULL
   OR OBJECT_ID(N'IFS.FVN_Supplier',N'U') IS NULL
   OR OBJECT_ID(N'MES.FVN_MaterialLot',N'U') IS NULL
    THROW 52903, 'Required part/supplier/material LOT tables are missing.', 1;

BEGIN TRY
    BEGIN TRANSACTION;

    IF OBJECT_ID(N'MES.FVN_Base36_5',N'FN') IS NULL
        EXEC(N'
        CREATE FUNCTION MES.FVN_Base36_5(@Value bigint)
        RETURNS char(5)
        AS
        BEGIN
            DECLARE @Digits varchar(36)=''0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ'';
            DECLARE @N bigint;
            DECLARE @Result varchar(5)='''' ;
            /* Alphabetic namespace avoids collisions with migration 028 numeric ItemId5 values. */
            IF @Value IS NULL OR @Value<0 OR @Value>=43670016 RETURN NULL;
            SET @N=@Value+16796160;
            WHILE @N>0
            BEGIN
                SET @Result=SUBSTRING(@Digits,CONVERT(int,(@N % 36)+1),1)+@Result;
                SET @N=@N/36;
            END;
            RETURN RIGHT(''00000''+@Result,5);
        END;');

    IF OBJECT_ID(N'MES.FVN_ItemIdentity',N'U') IS NULL
    BEGIN
        CREATE TABLE MES.FVN_ItemIdentity
        (
            ItemIdentityId bigint IDENTITY(1,1) NOT NULL,
            SiteCode nvarchar(30) NOT NULL,
            PartNo nvarchar(100) NOT NULL,
            ItemId5 char(5) NULL,
            CreatedAtUtc datetime2(3) NOT NULL CONSTRAINT DF_MES_FVN_ItemIdentity_Created DEFAULT(SYSUTCDATETIME()),
            CONSTRAINT PK_MES_FVN_ItemIdentity PRIMARY KEY(ItemIdentityId),
            CONSTRAINT UQ_MES_FVN_ItemIdentity_SitePart UNIQUE(SiteCode,PartNo)
        );
        CREATE UNIQUE INDEX UX_MES_FVN_ItemIdentity_ItemId5
            ON MES.FVN_ItemIdentity(ItemId5) WHERE ItemId5 IS NOT NULL;
    END;

    IF OBJECT_ID(N'MES.FVN_SupplierIdentity',N'U') IS NULL
    BEGIN
        CREATE TABLE MES.FVN_SupplierIdentity
        (
            SupplierIdentityId bigint IDENTITY(1,1) NOT NULL,
            SupplierCode nvarchar(60) NOT NULL,
            SupplierId5 char(5) NULL,
            SupplierName nvarchar(250) NOT NULL,
            CreatedAtUtc datetime2(3) NOT NULL CONSTRAINT DF_MES_FVN_SupplierIdentity_Created DEFAULT(SYSUTCDATETIME()),
            CONSTRAINT PK_MES_FVN_SupplierIdentity PRIMARY KEY(SupplierIdentityId),
            CONSTRAINT UQ_MES_FVN_SupplierIdentity_Supplier UNIQUE(SupplierCode)
        );
        CREATE UNIQUE INDEX UX_MES_FVN_SupplierIdentity_SupplierId5
            ON MES.FVN_SupplierIdentity(SupplierId5) WHERE SupplierId5 IS NOT NULL;
    END;

    /* Preserve the already-issued ItemId5 tokens from migration 028. */
    INSERT MES.FVN_ItemIdentity(SiteCode,PartNo,ItemId5)
    SELECT p.SiteCode,p.PartNo,p.ItemId5
    FROM dbo.FVN_PartIdentity p
    WHERE NOT EXISTS
    (
        SELECT 1 FROM MES.FVN_ItemIdentity i
        WHERE i.SiteCode=p.SiteCode AND i.PartNo=p.PartNo
    );

    /* SupplierCode is exactly IFS SUPPLIER_ID; it is not cast to a number. */
    INSERT MES.FVN_SupplierIdentity(SupplierCode,SupplierName)
    SELECT s.SupplierCode,s.SupplierName
    FROM IFS.FVN_Supplier s
    WHERE NOT EXISTS
    (
        SELECT 1 FROM MES.FVN_SupplierIdentity i
        WHERE i.SupplierCode=s.SupplierCode
    );

    EXEC(N'
    CREATE PROCEDURE MES.usp_FVN_AllocateItemId5
        @SiteCode nvarchar(30),
        @PartNo nvarchar(100),
        @ItemId5 char(5) OUTPUT
    AS
    BEGIN
        SET NOCOUNT ON;
        SET XACT_ABORT ON;
        SET @ItemId5=NULL;
        IF NULLIF(LTRIM(RTRIM(@SiteCode)),N'''') IS NULL
            THROW 52910, ''SiteCode is required.'', 1;
        IF NULLIF(LTRIM(RTRIM(@PartNo)),N'''') IS NULL
            THROW 52911, ''PartNo is required.'', 1;
        IF NOT EXISTS(SELECT 1 FROM IFS.FVN_InventoryPart WHERE SiteCode=@SiteCode AND PartNo=@PartNo)
            THROW 52912, ''Part does not exist in synchronized IFS inventory master.'', 1;

        BEGIN TRY
            BEGIN TRANSACTION;
            DECLARE @Lock int,@IdentityId bigint,@Candidate char(5);
            EXEC @Lock=sys.sp_getapplock
                @Resource=N''MES.FVN_ItemIdentity.Allocator'',
                @LockMode=''Exclusive'',@LockOwner=''Transaction'',@LockTimeout=15000;
            IF @Lock<0 THROW 52913, ''Cannot lock ItemId5 allocator.'', 1;

            SELECT @ItemId5=ItemId5
            FROM MES.FVN_ItemIdentity WITH(UPDLOCK,HOLDLOCK)
            WHERE SiteCode=@SiteCode AND PartNo=@PartNo;

            IF @ItemId5 IS NULL
            BEGIN
                IF NOT EXISTS(SELECT 1 FROM MES.FVN_ItemIdentity WHERE SiteCode=@SiteCode AND PartNo=@PartNo)
                    INSERT MES.FVN_ItemIdentity(SiteCode,PartNo,ItemId5)
                    VALUES(@SiteCode,@PartNo,NULL);

                SELECT @IdentityId=ItemIdentityId
                FROM MES.FVN_ItemIdentity WITH(UPDLOCK,HOLDLOCK)
                WHERE SiteCode=@SiteCode AND PartNo=@PartNo;

                SET @Candidate=MES.FVN_Base36_5(@IdentityId);
                WHILE EXISTS(SELECT 1 FROM MES.FVN_ItemIdentity WHERE ItemId5=@Candidate AND ItemIdentityId<>@IdentityId)
                BEGIN
                    DELETE MES.FVN_ItemIdentity WHERE ItemIdentityId=@IdentityId;
                    INSERT MES.FVN_ItemIdentity(SiteCode,PartNo,ItemId5)
                    VALUES(@SiteCode,@PartNo,NULL);
                    SET @IdentityId=CONVERT(bigint,SCOPE_IDENTITY());
                    SET @Candidate=MES.FVN_Base36_5(@IdentityId);
                END;
                UPDATE MES.FVN_ItemIdentity SET ItemId5=@Candidate WHERE ItemIdentityId=@IdentityId;
                SET @ItemId5=@Candidate;
            END;
            COMMIT TRANSACTION;
        END TRY
        BEGIN CATCH
            IF XACT_STATE()<>0 ROLLBACK TRANSACTION;
            THROW;
        END CATCH;
    END;');

    EXEC(N'
    CREATE PROCEDURE MES.usp_FVN_AllocateSupplierId5
        @SupplierCode nvarchar(60),
        @SupplierId5 char(5) OUTPUT
    AS
    BEGIN
        SET NOCOUNT ON;
        SET XACT_ABORT ON;
        SET @SupplierId5=NULL;
        IF NULLIF(LTRIM(RTRIM(@SupplierCode)),N'''') IS NULL
            THROW 52920, ''SupplierCode is required.'', 1;

        DECLARE @SupplierName nvarchar(250);
        SELECT @SupplierName=SupplierName FROM IFS.FVN_Supplier WHERE SupplierCode=@SupplierCode;
        IF @SupplierName IS NULL
            THROW 52921, ''SupplierCode does not exist in synchronized IFS supplier master.'', 1;

        BEGIN TRY
            BEGIN TRANSACTION;
            DECLARE @Lock int,@IdentityId bigint,@Candidate char(5);
            EXEC @Lock=sys.sp_getapplock
                @Resource=N''MES.FVN_SupplierIdentity.Allocator'',
                @LockMode=''Exclusive'',@LockOwner=''Transaction'',@LockTimeout=15000;
            IF @Lock<0 THROW 52922, ''Cannot lock SupplierId5 allocator.'', 1;

            SELECT @SupplierId5=SupplierId5
            FROM MES.FVN_SupplierIdentity WITH(UPDLOCK,HOLDLOCK)
            WHERE SupplierCode=@SupplierCode;

            IF @SupplierId5 IS NULL
            BEGIN
                IF NOT EXISTS(SELECT 1 FROM MES.FVN_SupplierIdentity WHERE SupplierCode=@SupplierCode)
                    INSERT MES.FVN_SupplierIdentity(SupplierCode,SupplierName,SupplierId5)
                    VALUES(@SupplierCode,@SupplierName,NULL);
                ELSE
                    UPDATE MES.FVN_SupplierIdentity SET SupplierName=@SupplierName
                    WHERE SupplierCode=@SupplierCode;

                SELECT @IdentityId=SupplierIdentityId
                FROM MES.FVN_SupplierIdentity WITH(UPDLOCK,HOLDLOCK)
                WHERE SupplierCode=@SupplierCode;
                SET @Candidate=MES.FVN_Base36_5(@IdentityId);
                WHILE EXISTS(SELECT 1 FROM MES.FVN_SupplierIdentity WHERE SupplierId5=@Candidate AND SupplierIdentityId<>@IdentityId)
                BEGIN
                    DELETE MES.FVN_SupplierIdentity WHERE SupplierIdentityId=@IdentityId;
                    INSERT MES.FVN_SupplierIdentity(SupplierCode,SupplierName,SupplierId5)
                    VALUES(@SupplierCode,@SupplierName,NULL);
                    SET @IdentityId=CONVERT(bigint,SCOPE_IDENTITY());
                    SET @Candidate=MES.FVN_Base36_5(@IdentityId);
                END;
                UPDATE MES.FVN_SupplierIdentity
                   SET SupplierId5=@Candidate,SupplierName=@SupplierName
                 WHERE SupplierIdentityId=@IdentityId;
                SET @SupplierId5=@Candidate;
            END
            ELSE
                UPDATE MES.FVN_SupplierIdentity SET SupplierName=@SupplierName
                WHERE SupplierCode=@SupplierCode;
            COMMIT TRANSACTION;
        END TRY
        BEGIN CATCH
            IF XACT_STATE()<>0 ROLLBACK TRANSACTION;
            THROW;
        END CATCH;
    END;');

    /* Backfill missing item identities for all existing IFS parts without changing issued tokens. */
    DECLARE @Site nvarchar(30),@Part nvarchar(100),@ItemToken char(5);
    DECLARE item_cursor CURSOR LOCAL FAST_FORWARD FOR
        SELECT ip.SiteCode,ip.PartNo
        FROM IFS.FVN_InventoryPart ip
        LEFT JOIN MES.FVN_ItemIdentity i
          ON i.SiteCode=ip.SiteCode AND i.PartNo=ip.PartNo
        WHERE i.ItemId5 IS NULL
        ORDER BY ip.SiteCode,ip.PartNo;
    OPEN item_cursor;
    FETCH NEXT FROM item_cursor INTO @Site,@Part;
    WHILE @@FETCH_STATUS=0
    BEGIN
        EXEC MES.usp_FVN_AllocateItemId5 @SiteCode=@Site,@PartNo=@Part,@ItemId5=@ItemToken OUTPUT;
        FETCH NEXT FROM item_cursor INTO @Site,@Part;
    END;
    CLOSE item_cursor;
    DEALLOCATE item_cursor;

    /* Allocate an internal token for every supplier already synchronized from IFS. */
    DECLARE @Supplier nvarchar(60),@SupplierToken char(5);
    DECLARE supplier_cursor CURSOR LOCAL FAST_FORWARD FOR
        SELECT SupplierCode FROM IFS.FVN_Supplier ORDER BY SupplierCode;
    OPEN supplier_cursor;
    FETCH NEXT FROM supplier_cursor INTO @Supplier;
    WHILE @@FETCH_STATUS=0
    BEGIN
        EXEC MES.usp_FVN_AllocateSupplierId5 @SupplierCode=@Supplier,@SupplierId5=@SupplierToken OUTPUT;
        FETCH NEXT FROM supplier_cursor INTO @Supplier;
    END;
    CLOSE supplier_cursor;
    DEALLOCATE supplier_cursor;

    /* Keep the compatibility dbo.FVN_PartIdentity projection synchronized with the MES identity master.
       Migration 028's existing IFS Apply procedure still writes this legacy projection. */
    EXEC(N'
    CREATE TRIGGER dbo.tr_FVN_PartIdentity_IdentitySync
    ON dbo.FVN_PartIdentity
    AFTER INSERT, UPDATE
    AS
    BEGIN
        SET NOCOUNT ON;
        IF EXISTS
        (
            SELECT 1
            FROM inserted i
            INNER JOIN MES.FVN_ItemIdentity m
              ON m.SiteCode=i.SiteCode AND m.PartNo=i.PartNo
            WHERE i.ItemId5 IS NOT NULL AND m.ItemId5 IS NOT NULL
              AND i.ItemId5<>m.ItemId5
        )
            THROW 52950, ''Attempt to change an already-issued ItemId5 is not allowed.'', 1;

        INSERT MES.FVN_ItemIdentity(SiteCode,PartNo,ItemId5)
        SELECT i.SiteCode,i.PartNo,i.ItemId5
        FROM inserted i
        WHERE i.ItemId5 IS NOT NULL
          AND NOT EXISTS
          (
              SELECT 1 FROM MES.FVN_ItemIdentity m
              WHERE m.SiteCode=i.SiteCode AND m.PartNo=i.PartNo
          );

        UPDATE m SET ItemId5=i.ItemId5
        FROM MES.FVN_ItemIdentity m
        INNER JOIN inserted i ON i.SiteCode=m.SiteCode AND i.PartNo=m.PartNo
        WHERE m.ItemId5 IS NULL AND i.ItemId5 IS NOT NULL;
    END;');

    /* Refresh supplier identity name/tokens whenever a supplier is inserted or updated by IFS Apply. */
    EXEC(N'
    CREATE TRIGGER IFS.tr_FVN_SupplierIdentity_Upsert
    ON IFS.FVN_Supplier
    AFTER INSERT, UPDATE
    AS
    BEGIN
        SET NOCOUNT ON;
        DECLARE @Code nvarchar(60),@Token char(5);
        DECLARE c CURSOR LOCAL FAST_FORWARD FOR SELECT SupplierCode FROM inserted;
        OPEN c;
        FETCH NEXT FROM c INTO @Code;
        WHILE @@FETCH_STATUS=0
        BEGIN
            EXEC MES.usp_FVN_AllocateSupplierId5 @SupplierCode=@Code,@SupplierId5=@Token OUTPUT;
            FETCH NEXT FROM c INTO @Code;
        END;
        CLOSE c;
        DEALLOCATE c;
    END;');

    /* The canonical LOT builders now use only FVN-owned 5-character identity tokens. */
    EXEC(N'
    ALTER PROCEDURE MES.usp_FVN_BuildComponentLotNo
        @RequestDate date,
        @SiteCode nvarchar(30),
        @PartNo nvarchar(100),
        @SupplierCode nvarchar(60),
        @DocNo nvarchar(40),
        @LotNo nvarchar(120) OUTPUT,
        @ItemId5 char(5) OUTPUT
    AS
    BEGIN
        SET NOCOUNT ON;
        DECLARE @SupplierId5 char(5);
        SET @LotNo=NULL;
        SET @ItemId5=NULL;
        IF @RequestDate IS NULL THROW 52930, ''RequestDate is required.'', 1;
        IF NULLIF(LTRIM(RTRIM(@DocNo)),N'''') IS NULL
            THROW 52931, ''Receipt document number is required.'', 1;
        EXEC MES.usp_FVN_AllocateItemId5 @SiteCode=@SiteCode,@PartNo=@PartNo,@ItemId5=@ItemId5 OUTPUT;
        EXEC MES.usp_FVN_AllocateSupplierId5 @SupplierCode=@SupplierCode,@SupplierId5=@SupplierId5 OUTPUT;
        SET @LotNo=CONVERT(char(6),@RequestDate,12)+@SupplierId5+@ItemId5+LTRIM(RTRIM(@DocNo));
        IF LEN(@LotNo)>120 THROW 52932, ''Generated component LOT exceeds 120 characters.'', 1;
    END;');

    EXEC(N'
    ALTER PROCEDURE MES.usp_FVN_BuildProductionLotNo
        @RequestDate date,
        @SiteCode nvarchar(30),
        @PartNo nvarchar(100),
        @ShiftCode varchar(2),
        @LineCode varchar(3),
        @DepartmentCode varchar(4),
        @LotNo char(20) OUTPUT,
        @ItemId5 char(5) OUTPUT
    AS
    BEGIN
        SET NOCOUNT ON;
        SET @LotNo=NULL;
        SET @ItemId5=NULL;
        IF @RequestDate IS NULL THROW 52940, ''Production date is required.'', 1;
        IF LEN(LTRIM(RTRIM(ISNULL(@ShiftCode,''''))))<>2
            THROW 52941, ''ShiftCode must contain exactly two characters.'', 1;
        IF LEN(LTRIM(RTRIM(ISNULL(@LineCode,''''))))<>3
            THROW 52942, ''LineCode must contain exactly three characters.'', 1;
        IF LEN(LTRIM(RTRIM(ISNULL(@DepartmentCode,''''))))<>4
            THROW 52943, ''DepartmentCode must contain exactly four characters.'', 1;
        IF NOT EXISTS(SELECT 1 FROM dbo.FVN_ProductionLine
                      WHERE SiteCode=@SiteCode AND LineCode=@LineCode AND IsActive=1)
            THROW 52944, ''Production line is not configured or inactive for this site.'', 1;
        IF NOT EXISTS(SELECT 1 FROM dbo.FVN_ProductionDepartment
                      WHERE SiteCode=@SiteCode AND DepartmentCode=@DepartmentCode
                        AND LineCode=@LineCode AND IsActive=1)
            THROW 52945, ''Department is not configured or inactive for this site.'', 1;
        EXEC MES.usp_FVN_AllocateItemId5 @SiteCode=@SiteCode,@PartNo=@PartNo,@ItemId5=@ItemId5 OUTPUT;
        SET @LotNo=CONVERT(char(6),@RequestDate,12)+@ItemId5+@ShiftCode+@LineCode+@DepartmentCode;
        IF LEN(@LotNo)<>20 THROW 52946, ''Production LOT must be exactly 20 characters.'', 1;
    END;');

    /* Retain dbo.FVN_PartIdentity as a compatibility projection, not as the allocator. */
    EXEC(N'
    ALTER PROCEDURE dbo.usp_FVN_PartIdentity_AllocateItemId5
        @SiteCode nvarchar(30),
        @PartNo nvarchar(100),
        @ItemId5 char(5) OUTPUT
    AS
    BEGIN
        SET NOCOUNT ON;
        EXEC MES.usp_FVN_AllocateItemId5
            @SiteCode=@SiteCode,@PartNo=@PartNo,@ItemId5=@ItemId5 OUTPUT;
        IF EXISTS(SELECT 1 FROM dbo.FVN_PartIdentity WHERE SiteCode=@SiteCode AND PartNo=@PartNo)
            UPDATE dbo.FVN_PartIdentity SET ItemId5=@ItemId5 WHERE SiteCode=@SiteCode AND PartNo=@PartNo;
        ELSE
            INSERT dbo.FVN_PartIdentity(SiteCode,PartNo,ItemId5) VALUES(@SiteCode,@PartNo,@ItemId5);
    END;');

    INSERT MES.FVN_SchemaMigration(MigrationVersion,MigrationName)
    VALUES('029',N'FVN-owned item and supplier five-character identities');

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF XACT_STATE()<>0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
GO

SELECT MigrationVersion,MigrationName
FROM MES.FVN_SchemaMigration WHERE MigrationVersion='029';
SELECT TOP (20) SiteCode,PartNo,ItemIdentityId,ItemId5
FROM MES.FVN_ItemIdentity ORDER BY ItemIdentityId;
SELECT TOP (20) SupplierCode,SupplierName,SupplierIdentityId,SupplierId5
FROM MES.FVN_SupplierIdentity ORDER BY SupplierIdentityId;
GO
