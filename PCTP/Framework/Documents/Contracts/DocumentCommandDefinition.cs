using System;
using System.Collections.Generic;
using System.Collections.ObjectModel;
using System.Data;
using System.Linq;

namespace PCTP.Framework.Documents
{
    /// <summary>Where a stored-procedure argument comes from. SQL metadata cannot change this.</summary>
    public enum DocumentParameterSource
    {
        /// <summary>Supplied by the caller (typed, validated, undeclared keys rejected).</summary>
        Input,
        /// <summary>Always the signed-in actor; never taken from the caller.</summary>
        Actor,
        /// <summary>The site that was authorized for the command.</summary>
        Site,
        /// <summary>A fresh idempotency key generated by the dispatcher.</summary>
        IdempotencyKey
    }

    public sealed class DocumentParameterDefinition
    {
        public string Name { get; private set; }
        public SqlDbType DbType { get; private set; }
        public DocumentParameterSource Source { get; private set; }
        public int Size { get; private set; }
        public byte Precision { get; private set; }
        public byte Scale { get; private set; }
        /// <summary>UI hint only: field whose value pre-fills this input. Never trusted by the dispatcher.</summary>
        public string SourceFieldCode { get; private set; }

        public DocumentParameterDefinition(string name, SqlDbType dbType, DocumentParameterSource source,
            int size = 0, byte precision = 0, byte scale = 0, string sourceFieldCode = null)
        {
            Name = DocumentIdentifiers.Identifier(name, "name");
            DbType = dbType;
            Source = source;
            Size = size;
            Precision = precision;
            Scale = scale;
            SourceFieldCode = string.IsNullOrWhiteSpace(sourceFieldCode)
                ? null : DocumentIdentifiers.Identifier(sourceFieldCode, "sourceFieldCode");

            bool isText = dbType == SqlDbType.NVarChar || dbType == SqlDbType.VarChar ||
                          dbType == SqlDbType.NChar || dbType == SqlDbType.Char;
            if (isText && size <= 0)
                throw new ArgumentException("Text parameter requires a size: " + name, "size");
            if (dbType == SqlDbType.Decimal && precision == 0)
                throw new ArgumentException("Decimal parameter requires a precision: " + name, "precision");
        }
    }

    public sealed class DocumentCommandDefinition
    {
        public string CommandCode { get; private set; }
        /// <summary>RBAC function code, e.g. MES.COMPONENT_ISSUE.</summary>
        public string PermissionCode { get; private set; }
        /// <summary>RBAC action code, e.g. CONFIRM.</summary>
        public string ActionCode { get; private set; }
        /// <summary>Bracket-quoted two-part procedure name registered in code.</summary>
        public string ProcedureName { get; private set; }
        public bool RequiresWorkflowTransition { get; private set; }
        /// <summary>Target status of the workflow transition. Required by the workflow gate (fail-closed when null).</summary>
        public int? WorkflowTargetStatus { get; private set; }
        public IReadOnlyList<DocumentParameterDefinition> Parameters { get; private set; }

        public DocumentCommandDefinition(string commandCode, string permissionCode, string actionCode,
            string procedureName, bool requiresWorkflowTransition,
            IEnumerable<DocumentParameterDefinition> parameters, int? workflowTargetStatus = null)
        {
            CommandCode = DocumentIdentifiers.Code(commandCode, "CommandCode");
            PermissionCode = DocumentIdentifiers.FunctionCode(permissionCode, "PermissionCode");
            ActionCode = DocumentIdentifiers.Code(actionCode, "ActionCode");
            ProcedureName = DocumentIdentifiers.SqlObject(procedureName, "ProcedureName");
            RequiresWorkflowTransition = requiresWorkflowTransition;
            if (workflowTargetStatus.HasValue && !requiresWorkflowTransition)
                throw new ArgumentException("workflowTargetStatus requires requiresWorkflowTransition.", "workflowTargetStatus");
            WorkflowTargetStatus = workflowTargetStatus;

            var items = (parameters ?? Enumerable.Empty<DocumentParameterDefinition>()).ToList();
            if (items.Any(p => p == null)) throw new ArgumentException("Null parameter definition.", "parameters");
            if (items.GroupBy(p => p.Name, StringComparer.OrdinalIgnoreCase).Any(g => g.Count() > 1))
                throw new ArgumentException("Duplicate parameter name in command " + CommandCode + ".", "parameters");
            foreach (DocumentParameterSource single in new[]
                { DocumentParameterSource.Actor, DocumentParameterSource.Site, DocumentParameterSource.IdempotencyKey })
            {
                if (items.Count(p => p.Source == single) > 1)
                    throw new ArgumentException("More than one " + single + " parameter in command " + CommandCode + ".", "parameters");
            }
            Parameters = new ReadOnlyCollection<DocumentParameterDefinition>(items);
        }
    }
}
